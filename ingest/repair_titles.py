def build_chapter_vocabulary(page_texts: list[str]) -> Vocabulary:
    """Vocabulary from the chapter's *body* text: heading-like lines are excluded, because a
    fragmented heading left in the body would otherwise validate its own fragments."""
    vocab = Vocabulary()
    for text in page_texts:
        for line in text.splitlines():
            stripped = line.strip()
            if not stripped:
                continue
            letters_only = [c for c in stripped if c.isalpha()]
            if letters_only and sum(1 for c in letters_only if c.isupper()) / len(letters_only) > 0.85:
                continue  # an all-caps line is a heading, not body prose
            if NUMBERED_HEADING.match(stripped):
                continue  # numbered heading or numbered exercise item
            vocab.add_text(stripped)
    return vocab


def repair_syllabus(
    syllabus: dict,
    pdf_dir: Path,
    page_texts: dict[tuple[str, int], list[str]],
    *,
    refold: bool = True,
) -> tuple[dict, list[dict]]:
    """Repair every fragmented title in the syllabus. Returns (syllabus, report rows).

    `page_texts` maps (book_code, chapter_no) -> the chapter's extracted page texts, used to build
    each chapter's vocabulary. The syllabus dict is modified in place and also returned.
    """
    report: list[dict] = []
    for subject in syllabus["subjects"]:
        code = subject["book_code"]
        for chapter in subject["chapters"]:
            sections = chapter.get("sections") or []
            if not sections:
                continue
            vocab = build_chapter_vocabulary(page_texts.get((code, chapter["no"]), []))
            pdf_path = pdf_dir / f"{code}{chapter['no']:02d}.pdf"
            for section in sections:
                original = section.get("title", "")
                render = None
                if refold and looks_fragmented(original) and pdf_path.exists():
                    try:
                        render = refold_heading(pdf_path, section.get("page") or 1, section["no"])
                    except Exception:  # a corrupt page must not stop the repair run
                        render = None
                outcome = repair_title(original, vocab, render=render)
                if outcome["status"] == "repaired":
                    section["title"] = outcome["title"]
                    section.pop("title_needs_review", None)
                elif outcome["status"] == "needs_review":
                    section["title_needs_review"] = True
                else:
                    section.pop("title_needs_review", None)
                if outcome["status"] != "clean":
                    report.append({
                        "subject": subject["id"], "chapter_no": chapter["no"],
                        "section_no": section["no"], "page": section.get("page"),
                        "status": outcome["status"], "method": outcome["method"],
                        "extracted": original, "title": section["title"],
                    })
    return syllabus, report


def load_page_texts(cache_dir: Path | None, pdf_dir: Path, subjects: list[dict]) -> dict:
    """Page texts per chapter, from the corpus page cache when present, else from the PDFs."""
    from ingest.extract_text import extract_document  # local import: avoids a cycle

    out: dict[tuple[str, int], list[str]] = {}
    for subject in subjects:
        code = subject["book_code"]
        for chapter in subject["chapters"]:
            pdf_path = pdf_dir / f"{code}{chapter['no']:02d}.pdf"
            cached = (cache_dir / f"{code}{chapter['no']:02d}.jsonl") if cache_dir else None
            if cached and cached.exists():
                pages = []
                for line in cached.read_text(encoding="utf-8").splitlines():
                    if line.strip():
                        pages.append(json.loads(line)["text"])
                out[(code, chapter["no"])] = pages
            elif pdf_path.exists():
                out[(code, chapter["no"])] = [p.text for p in extract_document(pdf_path).pages]
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--pdf-dir", required=True)
    ap.add_argument("--syllabus", default="data/syllabus/class10.json")
    ap.add_argument("--page-cache", default="corpus/pages")
    ap.add_argument("--no-refold", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    syllabus_path = Path(args.syllabus)
    syllabus = json.loads(syllabus_path.read_text(encoding="utf-8"))
    pdf_dir = Path(args.pdf_dir)
    cache = Path(args.page_cache)
    page_texts = load_page_texts(cache if cache.exists() else None, pdf_dir, syllabus["subjects"])
    syllabus, report = repair_syllabus(syllabus, pdf_dir, page_texts, refold=not args.no_refold)

    repaired = [r for r in report if r["status"] == "repaired"]
    review = [r for r in report if r["status"] == "needs_review"]
    print(f"fragmented titles found: {len(report)}  repaired: {len(repaired)}  needs_review: {len(review)}")
    for row in report:
        print(f"  [{row['status']:12s}] {row['subject']} §{row['section_no']:7s} "
              f"{row['extracted']!r} -> {row['title']!r} ({row['method']})"
              + (f"  note: {row['note']}" if row.get("note") else ""))
    if not args.dry_run:
        syllabus_path.write_text(json.dumps(syllabus, indent=1, ensure_ascii=False) + "\n",
                                 encoding="utf-8")
        print(f"wrote {syllabus_path}")
    return 0


