#!/usr/bin/env python3
"""Repair section titles that the source PDF's duplicate text layer split into fragments.

Diagnosis (measured on the real books, not assumed)
---------------------------------------------------
NCERT draws an all-caps parent heading several times at sub-point offsets. Each draw is a
*partial* render of the same string, placed at its true x position, so folding the copies by
vertical proximity and reading the widest one yields a concatenation of overlapping fragments
instead of the heading. Two shapes of damage come out of that fold:

    '1.1 CHEMICAL EQUA AL EQUATIONS'          (the true string is '1.1 CHEMICAL EQUATIONS')
    'HA HA VE YOU OBSERVED THE EFFECTS OF O XID TION'
                                              (true: 'HAVE YOU OBSERVED THE EFFECTS OF OXIDATION')

In both cases the fragments are *overlapping copies* of one string: split the fragment text at
the right place and a suffix of the left half equals a prefix of the right half. Removing that
duplicated span rebuilds the title. That is the whole trick, and it needs no external word list.

Rules used here (bounded, and every rewrite is verified)
-------------------------------------------------------
1. A title is *fragmented* when either (a) some split of its letters has a >= 3-character suffix
   equal to the next prefix, or (b) its first two words are the same word repeated ('HA HA',
   'MA MA', 'FA 11.5 FA'), which is the same defect at word granularity.
2. Candidates are generated by collapsing a duplicated leading word and by overlap-joining
   adjacent fragments (longest overlap first).
3. A candidate is accepted only when it is found, case-insensitively, in the chapter's own
   vocabulary — the n-grams of the chapter's extracted body text. Nothing is invented: a repair
   either matches the book's own prose or the title is left alone and flagged.
4. A second, independent route exists for titles the fold damaged beyond joining: re-read the
   heading's span cluster and keep the *most complete* render (see `refold_heading`). That text
   also has to pass rule 3 before it is used.
5. Titles that no route repairs keep their extracted text and gain `title_needs_review: true`.

Usage (usually driven by `python -m ingest.cli --repair-titles`):
    python -m ingest.repair_titles --pdf-dir <dir> --syllabus data/syllabus/class10.json
"""

from __future__ import annotations

import argparse
import json
import re
from dataclasses import dataclass
from pathlib import Path

try:
    import pymupdf  # new name
except ImportError:  # pragma: no cover - older wheels
    import fitz as pymupdf  # type: ignore

LETTERS = re.compile(r"[A-Za-z]+")
WORD = re.compile(r"[A-Za-z][A-Za-z'\-]*")
NUMBERED_HEADING = re.compile(r"^\s*(\d+(?:\.\d+){1,2})\b")

# A fragment overlap shorter than this is coincidence, not the duplicate-layer defect: it fires on
# clean titles such as 'Refining of Metals' ('refin|ing') and 'Trigonometric Identities'.
MIN_OVERLAP = 3
# A render is trusted only if the read covers >= 98% of the heading's width: anything less means
# part of the heading was never drawn in the copy that was read, so words are missing.
TRUST_COMPLETENESS = 0.98
# Words of up to this many characters are candidates when re-segmenting a rebuilt letter string.
MAX_WORD_LEN = 24
# n-gram width kept from the body text when building the chapter vocabulary.
MAX_PHRASE_WORDS = 8
SPAN_MERGE_TOLERANCE = 3.0
# Horizontal gap above which two spans on the same line are separate words rather than one word
# split across spans. A space in the 14pt heading font is ~3.5pt wide, so 1.0pt is generous.
SPAN_JOIN_GAP = 1.0
DIGITS = re.compile(r"\d")
LABELISH = re.compile(r"\b(activity|figure|fig\.?|table|box|example|exercise|solution|caution|"
                      r"note|experiment|problem|do you know|more to know)\b", re.IGNORECASE)


def letters(text: str) -> str:
    """Case-folded letters only: punctuation, digits and spacing are dropped for matching."""
    return "".join(LETTERS.findall(text)).lower()


def words_in(text: str) -> list[str]:
    return WORD.findall(text)


def overlap_splits(joined: str, min_overlap: int = MIN_OVERLAP) -> list[tuple[int, int]]:
    """Split points where a >= min_overlap suffix of the left part equals a prefix of the right."""
    hits: list[tuple[int, int]] = []
    for split in range(1, len(joined)):
        left, right = joined[:split], joined[split:]
        for size in range(min(len(left), len(right)), min_overlap - 1, -1):
            if left[-size:] == right[:size]:
                hits.append((split, size))
                break
    return hits


def duplicated_leading_word(title: str) -> bool:
    ws = words_in(title)
    return len(ws) >= 2 and len(ws[0]) >= 2 and ws[0].lower() == ws[1].lower()


def looks_fragmented(title: str, min_overlap: int = MIN_OVERLAP) -> bool:
    """True when the title carries the duplicate-layer defect (rule 1 in the module docstring)."""
    if duplicated_leading_word(title):
        return True
    return bool(overlap_splits(letters(title), min_overlap))


class Vocabulary:
    """The chapter's own words and phrases, keyed by case-folded letters.

    `phrases` maps 'chemicalequations' -> 'Chemical Equations' (first spelling seen in the body),
    so a repaired title can be rendered in the book's own wording and capitalisation.
    """

    def __init__(self) -> None:
        self.phrases: dict[str, str] = {}
        self.unigrams: set[str] = {"a", "i"}

    def add_text(self, text: str) -> None:
        for line in text.splitlines():
            tokens = words_in(line)
            for i in range(len(tokens)):
                for n in range(1, min(MAX_PHRASE_WORDS, len(tokens) - i) + 1):
                    phrase = tokens[i : i + n]
                    key = "".join(t.lower() for t in phrase)
                    if key and key not in self.phrases:
                        self.phrases[key] = " ".join(phrase)
            for token in tokens:
                self.unigrams.add(token.lower())

    def segment(self, joined: str) -> list[str] | None:
        """Split a letter string into the fewest chapter words that spell it, or None."""
        n = len(joined)
        best: list[list[str] | None] = [None] * (n + 1)
        best[0] = []
        for i in range(n):
            if best[i] is None:
                continue
            for j in range(i + 2, min(n, i + MAX_WORD_LEN) + 1):
                piece = joined[i:j]
                if piece in self.unigrams:
                    if best[j] is None or len(best[i]) + 1 < len(best[j]):  # type: ignore[arg-type]
                        best[j] = [*best[i], piece]  # type: ignore[misc]
        return best[n]


def candidates(title: str) -> list[tuple[str, str]]:
    """(letters, how) candidates for the repaired title, best-guess order first."""
    out: list[tuple[str, str]] = []
    seen: set[str] = set()

    def push(text: str, how: str) -> None:
        key = letters(text)
        if key and key not in seen:
            seen.add(key)
            out.append((key, how))

    word_list = words_in(title)
    collapsed = list(word_list)
    while len(collapsed) >= 2 and collapsed[0].lower() == collapsed[1].lower():
        collapsed.pop(1)

    for tokens, how_prefix in ((word_list, ""), (collapsed, "collapse+join:")):
        for split in range(1, len(tokens)):
            left = letters(" ".join(tokens[:split]))
            right = letters(" ".join(tokens[split:]))
            for size in range(min(len(left), len(right)), 0, -1):
                if size and left[-size:] == right[:size]:
                    push(left + right[size:], f"{how_prefix}overlap-join:{size}")
                    break
    if collapsed != word_list:
        push(" ".join(collapsed), "collapse-duplicate")
    return out


def apply_case(repaired: str, original: str) -> str:
    """Keep the book's own convention: an all-caps heading stays all-caps."""
    letters_only = [c for c in original if c.isalpha()]
    if letters_only and sum(1 for c in letters_only if c.isupper()) / len(letters_only) >= 0.8:
        return repaired.upper()
    return repaired


def repair_title(title: str, vocab: Vocabulary, render: HeadingRender | None = None) -> dict:
    """Return {status, title, method, note} for one extracted section title.

    status: 'clean' (no defect detected) | 'repaired' | 'needs_review'.
    """
    if not looks_fragmented(title):
        return {"status": "clean", "title": title, "method": None, "note": None}

    # Route 1: a complete render of the heading, read straight from the PDF's own glyphs. The gate
    # is geometric: the read must cover the heading's full width and must agree with every span of
    # the cluster (each copy is a partial render, so its text has to appear in the true heading).
    # The chapter's vocabulary is then used only to prefer the book's own spelling of that text.
    if render is not None and render.completeness >= TRUST_COMPLETENESS and render.consistent:
        text = strip_leading_number(render.text)
        note = None
        if render.tail:
            # The heading wrapped and a same-size line follows it. That join is a guess about the
            # layout, so unlike the read itself it has to be verified: the joined text must be a
            # phrase of the chapter's own vocabulary, or failing that the second line's own words
            # must all be words the chapter uses. Otherwise the second line is reported rather than
            # invented, and the verified read stands.
            combined = f"{text} {render.tail}"
            key = letters(combined)
            if key in vocab.phrases:
                return {"status": "repaired", "title": apply_case(vocab.phrases[key], title),
                        "method": "refold+wrapped", "note": combined}
            if vocab.segment(key) or vocab.segment(letters(render.tail)):
                return {"status": "repaired", "title": apply_case(combined, title),
                        "method": "refold+wrapped", "note": combined}
            note = f"unjoined second line: {render.tail!r}"
        key = letters(text)
        if key in vocab.phrases:
            return {"status": "repaired", "title": apply_case(vocab.phrases[key], title),
                    "method": "refold", "note": note or text}
        return {"status": "repaired", "title": apply_case(text, title),
                "method": "refold", "note": note or text}

    # Route 2: rebuild by overlap-joining the fragments, accepted only on a vocabulary match.
    for key, how in candidates(title):
        if key in vocab.phrases:
            return {"status": "repaired", "title": apply_case(vocab.phrases[key], title),
                    "method": how, "note": None}
    for key, how in candidates(title):
        pieces = vocab.segment(key)
        if pieces:
            return {"status": "repaired", "title": apply_case(" ".join(pieces), title),
                    "method": f"{how}+segment", "note": None}
    return {"status": "needs_review", "title": title, "method": None,
            "note": "no candidate matches the chapter's own vocabulary"}



# --------------------------------------------------------------------------------------
# Re-reading a heading's own span cluster (route 2). Reuses the clustering tolerance and the
# span-collection of ingest/extract_structure.py; the difference is in how the copies are
# scored: the extractor keeps the widest copy, which is often a truncated render, while this
# keeps the copy that covers the heading's full extent with the fewest gaps and overlaps.
# --------------------------------------------------------------------------------------


def _spans_of(page) -> list[dict]:
    spans = []
    for block in page.get_text("dict")["blocks"]:
        for line in block.get("lines", []):
            for span in line.get("spans", []):
                if span["text"].strip():
                    spans.append(span)
    return spans


def _clusters(spans: list[dict], tolerance: float = SPAN_MERGE_TOLERANCE) -> list[list[dict]]:
    ordered = sorted(spans, key=lambda s: ((s["bbox"][1] + s["bbox"][3]) / 2, s["bbox"][0]))
    clusters: list[list[dict]] = []
    for span in ordered:
        centre = (span["bbox"][1] + span["bbox"][3]) / 2
        for cluster in clusters:
            ref = (cluster[0]["bbox"][1] + cluster[0]["bbox"][3]) / 2
            if abs(centre - ref) <= tolerance:
                cluster.append(span)
                break
        else:
            clusters.append([span])
    return clusters


def strip_leading_number(text: str) -> str:
    """'1.3 HAVE YOU OBSERVED ...' -> 'HAVE YOU OBSERVED ...' (the syllabus wants the title)."""
    return re.sub(r"^\s*\d+(?:\.\d+){1,2}\s+", "", text).strip()


@dataclass
class HeadingRender:
    """One render of a heading, with the measurements that decide whether to trust its text."""

    text: str
    completeness: float   # covered width / the heading's full extent
    overlap: float        # characters dropped as duplicated fragments while reading it
    consistent: bool = True   # every span of the cluster is a substring of this text
    tail: str = ""            # a wrapped heading's next line, if one follows this cluster



def _read_copy(pieces: list[tuple[dict, int]]) -> str:
    """Join the pieces in reading order: a space only where the source glyphs had a real gap.

    Spans drawn contiguously are one word split across spans ('HA' + 'VE'), so no space goes between
    them; a span entered mid-way keeps whatever word break the source text had at the cut.
    """
    if not pieces:
        return ""
    text = pieces[0][0]["text"][pieces[0][1]:]
    for (previous, _), (span, index) in zip(pieces, pieces[1:], strict=False):
        gap = span["bbox"][0] - previous["bbox"][2]
        cut_after_space = index > 0 and span["text"][index - 1] == " "
        text += (" " if gap > SPAN_JOIN_GAP or cut_after_space else "") + span["text"][index:]
    return re.sub(r"\s{2,}", " ", text).strip()


def _cover_chain(spans: list[dict], gap_tolerance: float = 6.0) -> tuple[list[tuple[dict, int]], float, float]:
    """Read a line left to right by tiling it, returning (pieces, start_x, end_x).

    The copies of one render cannot be separated by geometry alone — their y tops and centres both
    interleave with the other renders', so any grouping mixes them ('1.31.3 HAHAVE ...'). What does
    separate a real render is that its spans tile the line: each one starts where the previous
    ended, and the walk reaches the far edge.

    A span that *starts before* the cursor is entered mid-way and its text sliced from the cursor.
    That is what makes complementary renders work: '1.1 CHEMICAL EQUA' followed by 'AL EQUATIONS'
    (which starts inside it) reads as '1.1 CHEMICAL EQUATIONS' once the already-read 'AL EQUA' is cut
    off. The cut is estimated from character positions, so the result is always checked against the
    chapter's own vocabulary before it is used as a title.

    The gap allowance is a word space (~5pt at 14pt type): the fold has already dropped the
    whitespace-only spans, and a genuinely missing word is caught by the completeness test, which
    measures how much of the line's width the read covers.
    """
    ordered = sorted(spans, key=lambda s: (s["bbox"][0], -s["bbox"][2]))
    if not ordered:
        return [], 0.0, 0.0
    start = ordered[0]["bbox"][0]
    end = max(s["bbox"][2] for s in ordered)
    cursor = start
    pieces: list[tuple[dict, int]] = []
    while cursor < end - 0.5:
        candidates: list[tuple[float, dict, int]] = []
        for span in ordered:
            x0, x1 = span["bbox"][0], span["bbox"][2]
            if x1 <= cursor + 0.5 or x0 > cursor + gap_tolerance:
                continue
            text = span["text"]
            width = x1 - x0
            if x0 < cursor - 0.5:
                if width <= 0:
                    continue
                index = int(round((cursor - x0) / width * len(text)))
                if index >= len(text):
                    continue
            else:
                index = 0
            candidates.append((x1, span, index))
        if not candidates:
            break
        # Prefer a span that starts at the cursor: entering a span mid-way needs a character-position
        # estimate, so it is the fallback, not the first choice.
        flush = [item for item in candidates if item[2] == 0]
        x1, span, index = max(flush or candidates, key=lambda item: item[0])
        pieces.append((span, index))
        cursor = x1
    return pieces, start, end


def _continuation_line(page_spans: list[dict], cluster: list[dict], pieces: list[tuple[dict, int]],
                       cursor: float, column_right: float) -> str:
    """The next line of a heading that wrapped, or ''.

    A heading drawn in two lines puts the rest of its text at the same size on the line below, so
    that shape is what is looked for: same size, within one line's leading, in the heading's column.
    Label lines ('Activity 2.1') are excluded — those sit under headings all over these books. What
    is returned is only a *candidate*: the caller joins it and checks the result against the
    chapter's own vocabulary before it can become a title.
    """
    size = max(span["size"] for span, _ in pieces)
    bottom = max(span["bbox"][3] for span, _ in pieces)
    left = min(span["bbox"][0] for span in cluster)
    for candidate in _clusters(page_spans):
        if candidate is cluster:
            continue
        top = min(span["bbox"][1] for span in candidate)
        if not 0 < top - bottom <= 26:
            continue
        # Headings are not always flush left — a wrapped line can be indented — so the test is
        # "starts in the heading's column", not "starts at the same x".
        if min(span["bbox"][0] for span in candidate) > left + 60:
            continue
        if abs(max(span["size"] for span in candidate) - size) > 0.6:
            continue
        line = " ".join(span["text"] for span in sorted(candidate, key=lambda s: s["bbox"][0]))
        if LABELISH.search(line):
            continue
        # A line that starts with its own section number is the next section's heading, not this
        # heading's second line. Read the candidate the same way the heading itself is read — these
        # lines carry the duplicate layer too ('COMMON? COMMON? COMMON?') — and drop it if the read
        # is itself a fragmented copy of some other heading.
        if NUMBERED_HEADING.match(line.strip()):
            continue
        pieces, _, _ = _cover_chain(candidate)
        tail_text = _read_copy(pieces)
        if not tail_text or looks_fragmented(tail_text) or len(tail_text.split()) > 5:
            continue
        return tail_text
    return ""


def _consistent_with_spans(text: str, cluster: list[dict], min_chars: int = 6) -> bool:
    """Every span of the cluster must be a substring of the read.

    Each copy is a *partial* render of the same heading, so any span longer than a few characters
    has to appear verbatim in the true text. A read that contradicts a span has mis-sliced
    somewhere, and this is what catches it — without needing a word list.
    """
    flat = re.sub(r"\s+", " ", text)
    for span in cluster:
        piece = re.sub(r"\s+", " ", span["text"]).strip()
        if len(piece) >= min_chars and piece not in flat:
            return False
    return True


def best_heading_render(page, section_no: str) -> HeadingRender | None:
    """The most complete render of the heading for `section_no` on `page`, or None.

    `completeness` is how much of the heading's width the read covers, so a truncated render scores
    below 1 and is refused. `consistent` says whether the read agrees with every span of the cluster.
    """
    token = re.compile(rf"(?<![\d.]){re.escape(section_no)}(?![\d.])")
    page_spans = _spans_of(page)
    column_right = max((s["bbox"][2] for s in page_spans if s["size"] >= 8), default=0.0)
    best: tuple[float, HeadingRender] | None = None
    for cluster in _clusters(page_spans):
        joined = " ".join(s["text"].strip() for s in sorted(cluster, key=lambda s: s["bbox"][0]))
        # A heading line *begins* with its section number. Anchoring the token at the start keeps
        # body prose out of the search: 'Activity 1.1 can be described as …' and 'In reaction
        # (1.32) …' both contain the token and both score higher than the heading itself.
        if not token.match(joined.lstrip()):
            continue
        extent = max(s["bbox"][2] for s in cluster) - min(s["bbox"][0] for s in cluster)
        pieces, start, _ = _cover_chain(cluster)
        text = _read_copy(pieces)
        if not pieces or not token.match(text) or DIGITS.search(text) is None:
            continue
        cursor = max(span["bbox"][2] for span, _ in pieces)
        tail = _continuation_line(page_spans, cluster, pieces, cursor, column_right)
        completeness = (cursor - start) / extent if extent else 0.0
        skipped = sum(index for _, index in pieces)
        consistent = _consistent_with_spans(f"{text} {tail}".strip() if tail else text, cluster)
        # A read that agrees with its own spans outranks one that merely covers more of the line.
        score = (1000 if consistent else 0) + completeness * extent - skipped
        render = HeadingRender(text=text, completeness=round(completeness, 3),
                               overlap=float(skipped), consistent=consistent, tail=tail)
        if best is None or score > best[0]:
            best = (score, render)
    return best[1] if best else None


def refold_heading(pdf_path: Path, page_no: int, section_no: str) -> HeadingRender | None:
    doc = pymupdf.open(pdf_path)
    try:
        if not 1 <= page_no <= doc.page_count:
            return None
        return best_heading_render(doc[page_no - 1], section_no)
    finally:
        doc.close()



